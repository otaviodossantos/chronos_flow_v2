#!/usr/bin/env node
/**
 * Registra o estado atual do banco como a primeira migration, sem tocar nos
 * dados. Serve para bancos criados antes de o projeto adotar migrations.
 *
 * O SQL e gerado pelo proprio Prisma a partir do banco em uso, entao ele
 * corresponde exatamente ao que existe hoje — escrever esse arquivo a mao
 * abriria espaco para divergencias que so aparecem como "drift" mais tarde.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const NAME = '0_init';
const dir = path.join('prisma', 'migrations', NAME);

function databaseUrl() {
  if (process.env.DATABASE_URL) return process.env.DATABASE_URL;
  if (!existsSync('.env')) return null;
  for (const line of readFileSync('.env', 'utf8').split('\n')) {
    const match = line.match(/^\s*DATABASE_URL\s*=\s*"?([^"\n]+)"?\s*$/);
    if (match) return match[1];
  }
  return null;
}

const url = databaseUrl();
if (!url) {
  console.error('DATABASE_URL nao encontrada no ambiente nem no .env.');
  process.exit(1);
}

if (existsSync(path.join(dir, 'migration.sql'))) {
  console.log(`A migration ${NAME} ja existe. Nada a fazer.`);
  process.exit(0);
}

const run = (args) =>
  execFileSync('npx', ['prisma', ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });

console.log('Lendo o estado atual do banco...');
const sql = run(['migrate', 'diff', '--from-empty', '--to-url', url, '--script']);

if (!sql.trim() || sql.includes('-- This is an empty migration.')) {
  console.error(
    'O banco parece vazio. Nao ha o que registrar como baseline —\n' +
      'rode "npm run prisma:migrate" para criar a primeira migration do zero.',
  );
  process.exit(1);
}

mkdirSync(dir, { recursive: true });
writeFileSync(path.join(dir, 'migration.sql'), sql);
console.log(`Escrito prisma/migrations/${NAME}/migration.sql`);

// O Prisma exige este arquivo na pasta de migrations. Sem ele, `migrate dev`
// nao reconhece o historico e trata o banco como fora de sincronia.
const lock = path.join('prisma', 'migrations', 'migration_lock.toml');
if (!existsSync(lock)) {
  const provider = url.startsWith('mysql')
    ? 'mysql'
    : url.startsWith('sqlserver')
      ? 'sqlserver'
      : url.startsWith('file:')
        ? 'sqlite'
        : 'postgresql';
  writeFileSync(
    lock,
    '# Please do not edit this file manually\n' +
      '# It should be added in your version-control system (e.g., Git)\n' +
      `provider = "${provider}"\n`,
  );
  console.log('Escrito prisma/migrations/migration_lock.toml');
}

console.log('Marcando como ja aplicada (nenhum comando roda no banco)...');
run(['migrate', 'resolve', '--applied', NAME]);

console.log(
  '\nBaseline pronto. Agora rode:\n' +
    '  npm run prisma:migrate   # gera e aplica a migration das mudancas pendentes\n',
);
